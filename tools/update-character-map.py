"""Generate the browser's character table with Windows' Chinese conversion."""

import ctypes
import json
import re
import sys
from pathlib import Path


DIST = Path(__file__).resolve().parents[1] / "dist"
SOURCE_FILES = (
    "index.html", "index-data.js", "person-portraits.js", "work-summaries.js",
    "catalog.js", "app.js", "language.js",
)
CHINESE = re.compile(r"[\u3400-\u9fff]")
SIMPLIFIED_CHINESE = 0x02000000
VARIANTS = {
    "凜": "凛", "崑": "昆", "後": "后", "徵": "征", "慾": "欲",
    "於": "于", "暘": "旸", "癒": "愈", "蒐": "搜", "蠍": "蝎",
    "鍊": "炼", "鍠": "锽", "鑑": "鉴", "闇": "暗", "闍": "阇",
    "鵰": "雕", "麽": "么", "麼": "么", "齣": "出", "龑": "䶮",
}


def main():
    if sys.platform != "win32":
        sys.exit("Generate this table on Windows. The checked-in table works in any browser.")

    convert = ctypes.windll.kernel32.LCMapStringEx
    source = "".join((DIST / name).read_text(encoding="utf-8") for name in SOURCE_FILES)
    buffer = ctypes.create_unicode_buffer(8)
    mapping = {}
    for char in sorted(set(CHINESE.findall(source))):
        length = convert("zh-CN", SIMPLIFIED_CHINESE, char, 1, buffer, len(buffer), None, None, 0)
        if not length:
            raise OSError(f"Unable to convert U+{ord(char):04X}")
        if buffer.value != char:
            mapping[char] = buffer.value
    mapping.update(VARIANTS)

    contents = json.dumps(mapping, ensure_ascii=False, indent=2, sort_keys=True)
    (DIST / "character-map.js").write_text(
        "// Generated by tools/update-character-map.py.\n"
        f"const simplifiedCharacters = {contents};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
